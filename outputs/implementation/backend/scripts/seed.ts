// ─── Seed Function ─────────────────────────────────────────────────

async function seed() {
  const allQuestions: SeedQuestion[] = [...behavioral, ...technical, ...situational, ...roleSpecific]

  console.log(`Seeding ${allQuestions.length} questions...`)

  let inserted = 0
  for (const q of allQuestions) {
    const [row] = await db
      .insert(questions)
      .values({
        text: q.text,
        type: q.type,
        level: q.level,
        industry: q.industry,
        difficulty: q.difficulty,
        tags: q.tags,
        framework: q.framework ?? null,
        status: 'published',
      })
      .returning({ id: questions.id })

    await db.insert(questionAnswers).values({
      questionId: row.id,
      answerText: q.answer,
      keywords: q.keywords,
      isPrimary: true,
    })

    inserted++
  }

  console.log(`Done. Inserted ${inserted} questions with answers.`)
  process.exit(0)
}

seed().catch((err) => {
  console.error('Seed failed:', err)
  process.exit(1)
})
